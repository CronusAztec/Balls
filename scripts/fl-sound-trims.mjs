#!/usr/bin/env node
/**
 * --- fl-overhaul --- (Stage 4) Renders every Fight League sound recipe (src/lib/audio/flRecipes.ts `flAllRecipes()`) in
 * Chromium's OfflineAudioContext through flSynth.ts and writes src/lib/audio/flRecipeTrims.ts: per recipe and pitch H the gain
 * that brings its peak to its tier's (one-shot 0.40, charge 0.30, held 0.25 – `FL_TIER_PEAK`), so the mixer plays every row
 * at the same loudness whatever its own layer gains. Rendered at F = E4, R = C5, the variant in the middle, a held row held
 * 1 s. Run it after changing a recipe (tests/fightLeagueSound.test.ts fails on a row without a trim):
 *
 *   node scripts/fl-sound-trims.mjs           (CHROME_PATH=… to pick the browser; Playwright's Chromium by default)
 *
 * Needs esbuild and playwright (dev dependencies). Nothing is downloaded; nothing else is written.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "src", "lib", "audio", "flRecipeTrims.ts");

async function bundle() {
  const esbuild = await import("esbuild");
  const result = await esbuild.build({
    stdin: {
      contents: `
        import { scheduleFlRecipe, recipeDurationMs, parseFlRecipe } from "@/lib/audio/flSynth";
        import { flAllRecipes, flTrimKey, FL_TIER_PEAK, FL_TRIM_F, FL_TRIM_R, FL_TRIM_HOLD_SEC } from "@/lib/audio/flRecipes";
        window.flLib = { scheduleFlRecipe, recipeDurationMs, parseFlRecipe, flAllRecipes, flTrimKey, FL_TIER_PEAK, FL_TRIM_F, FL_TRIM_R, FL_TRIM_HOLD_SEC };
      `,
      resolveDir: ROOT,
      loader: "ts",
    },
    bundle: true,
    write: false,
    format: "iife",
    platform: "browser",
    target: "es2020",
    alias: { "@": path.join(ROOT, "src") },
    define: { "process.env.NEXT_PUBLIC_BASE_PATH": '""', "process.env.NEXT_PUBLIC_SITE_URL": '""', "process.env.NEXT_PUBLIC_SITE_DOMAIN": '""' },
    logLevel: "error",
  });
  return result.outputFiles[0].text;
}

const code = await bundle();
const { chromium } = await import("playwright");
const browser = await chromium.launch(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {});
try {
  const page = await browser.newPage();
  await page.setContent("<!doctype html><html><body></body></html>");
  await page.addScriptTag({ content: code });
  const rows = await page.evaluate(async () => {
    const lib = window.flLib;
    const seen = new Map();
    for (const e of lib.flAllRecipes()) {
      const key = lib.flTrimKey(e.text, e.h);
      if (seen.has(key)) continue;
      seen.set(key, e);
    }
    const out = [];
    for (const [key, e] of seen) {
      const r = lib.parseFlRecipe(e.text);
      const held = r.held || e.tier === "sustain";
      const sec = lib.recipeDurationMs(r, held ? lib.FL_TRIM_HOLD_SEC * 1000 : undefined) / 1000 + 0.3;
      const rate = 48000;
      const off = new OfflineAudioContext(2, Math.ceil(Math.min(4, Math.max(0.2, sec)) * rate), rate);
      lib.scheduleFlRecipe(off, off.destination, r, 0.01, { F: lib.FL_TRIM_F, R: lib.FL_TRIM_R, H: e.h, variant: 0.5, sustainSec: held ? lib.FL_TRIM_HOLD_SEC : undefined });
      const buf = await off.startRendering();
      let peak = 0;
      for (let c = 0; c < buf.numberOfChannels; c++) {
        const d = buf.getChannelData(c);
        for (let i = 0; i < d.length; i++) {
          const v = Math.abs(d[i]);
          if (v > peak) peak = v;
        }
      }
      const target = lib.FL_TIER_PEAK[e.tier];
      out.push({ key, peak, trim: peak > 1e-6 ? Math.max(0.05, Math.min(20, target / peak)) : 1, where: `${e.table} ${e.key} ${e.role}` });
    }
    return out;
  });
  rows.sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
  const silent = rows.filter((r) => !(r.peak > 1e-6));
  if (silent.length) console.warn("Silent recipes:", silent.map((r) => r.where).join(", "));
  const lines = rows.map((r) => `  ${JSON.stringify(r.key)}: ${Number(r.trim.toPrecision(4))},`);
  const text = `// GENERATED by scripts/fl-sound-trims.mjs – do not edit by hand (re-run it after changing a recipe of flRecipes.ts).
/**
 * --- fl-overhaul --- (Stage 4) The gain that brings each Fight League recipe's peak, rendered in Chromium at F = E4, R = C5
 * and its pitch H, to its tier's (one-shot 0.40, charge 0.30, held 0.25), keyed by \`flTrimKey(text, H)\`.
 */
export const FL_RECIPE_TRIMS: Readonly<Record<string, number>> = {
${lines.join("\n")}
};
`;
  fs.writeFileSync(OUT, text);
  const trims = rows.map((r) => r.trim).sort((a, b) => a - b);
  console.log(`${rows.length} recipes → ${path.relative(ROOT, OUT)} (trims ${trims[0].toFixed(3)} … ${trims[trims.length - 1].toFixed(3)}, median ${trims[Math.floor(trims.length / 2)].toFixed(3)})`);
} finally {
  await browser.close();
}
